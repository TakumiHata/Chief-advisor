const FAILURE_PATTERNS = `【よくある失敗パターンと対策】

■ ファネリング失敗
症状: イエティが外周を回り始める。中央の防衛が残る
原因: サイドカットが不十分、ファネリングユニット不足
対策: ウィザードを追加する。ヒーローで片側を確実にカット。投入前に必ず外周の建物を2〜3個壊す

■ インフェルノに焼かれる
症状: 0:25〜0:35でタンク系の残数が急減
原因: フリーズのタイミングが遅い、または単体インフェルノを放置
対策: インフェルノに到達する「前」にフリーズを構える。単体インフェルノは最優先フリーズ対象

■ 巨大爆弾で壊滅
症状: 特定の区画通過時にタンク・サポートがまとめて消える
原因: 巨爆2連配置ポイントに密集して突入
対策: ヒールを巨爆予想ゾーンに先置き。ユニットの投入を少し分散させる

■ イーグル砲の集中砲火
症状: 中盤以降、範囲ダメージでサポートユニットが次々に消える
原因: ウォーデンアビリティの温存ミス、イーグルへの対処なし
対策: イーグル起動直後にウォーデンアビリティ。可能ならフリーズも重ねる

■ CC援軍の処理失敗
症状: 援軍に釣られてユニットがバラける
原因: ポイズン不使用、援軍を無視して本隊を出した
対策: ポイズンをCC援軍に即投下。クイヒーで事前処理が理想

■ 呪文の使い切り / 温存しすぎ
症状: 攻撃終盤に呪文が余る or 序盤で使い切って後半が裸
対策: フリーズは最低1本を後半用に温存。レイジは防衛密集地帯に合わせる

■ ヒーローの無駄死に
症状: ヒーローが序盤で倒される。アビリティが無駄になる
原因: ヒーローを先出しして集中砲火を受けた
対策: タンクの後ろからヒーローを出す。アビリティのタイミングを意識する

■ 時間切れ (タイムフェイル)
症状: 95%〜99%で時間切れ
原因: ファネリングに時間をかけすぎ、残存施設が散在
対策: ファネリングは15秒以内に完了。ロイヤルチャンピオンを「裏取り」に使う`;

